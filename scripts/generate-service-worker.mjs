import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { relative, resolve, sep } from 'node:path'

const DIST_ROOT = resolve('dist')
const packVersionSource = await readFile(
  resolve('src/i18n/localePackVersion.ts'),
  'utf8',
)
const packVersionMatch = packVersionSource.match(
  /LOCALE_PACK_VERSION\s*=\s*(\d+)/u,
)
if (!packVersionMatch) {
  throw new Error('Unable to resolve LOCALE_PACK_VERSION for the service worker')
}
const localePackVersion = Number(packVersionMatch[1])

async function filesBelow(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const path = resolve(directory, entry.name)
    if (entry.isDirectory()) files.push(...await filesBelow(path))
    else files.push(path)
  }
  return files
}

const bundleFiles = (await filesBelow(resolve(DIST_ROOT, 'assets')))
  .filter((path) => /\.(?:css|js|woff2?)$/i.test(path))
  .sort()
const builtIndex = await readFile(resolve(DIST_ROOT, 'index.html'), 'utf8')
const directlyReferencedAssetUrls = new Set(
  [...builtIndex.matchAll(/(?:src|href)=["'](\/assets\/[^"']+)["']/gi)]
    .map((match) => match[1]),
)
if (directlyReferencedAssetUrls.size === 0) {
  throw new Error('Built index.html does not reference any direct shell assets')
}
const shellBundleFiles = bundleFiles.filter((path) => {
  const url = `/${relative(DIST_ROOT, path).split(sep).join('/')}`
  return directlyReferencedAssetUrls.has(url)
})
const publicShellFiles = [
  'favicon.svg',
  'site.webmanifest',
  'site.es.webmanifest',
  'site.zh-TW.webmanifest',
  'site.fr.webmanifest',
]
  .map((name) => resolve(DIST_ROOT, name))
const localeFiles = (await filesBelow(resolve(DIST_ROOT, 'locales')))
  .filter((path) => path.endsWith('.json'))
  .sort()
const precacheFiles = [...shellBundleFiles, ...publicShellFiles]
// Lazy chunks still rotate cache versions without being downloaded at install time.
const hashedFiles = [...bundleFiles, ...publicShellFiles, ...localeFiles]
const digest = createHash('sha256')
const urls = ['/', '/index.html']

for (const path of hashedFiles) {
  const bytes = await readFile(path)
  digest.update(relative(DIST_ROOT, path).split(sep).join('/'))
  digest.update(bytes)
  if (precacheFiles.includes(path)) {
    urls.push(`/${relative(DIST_ROOT, path).split(sep).join('/')}`)
  }
}

const revision = digest.digest('hex').slice(0, 16)
const source = `/* Generated by scripts/generate-service-worker.mjs. */
const SHELL_CACHE = ${JSON.stringify(`astral-shell-${revision}`)};
const LOCALE_CACHE_PREFIX = "astral-locales-v";
const LOCALE_CACHE = ${JSON.stringify(`astral-locales-v${localePackVersion}`)};
const REQUIRED_LOCALE_URL = "/locales/en.json";
const SHELL_URLS = ${JSON.stringify(urls)};
const SHELL_PATHS = new Set(SHELL_URLS.map((url) => new URL(url, self.location.origin).pathname));

self.addEventListener('install', (event) => {
  event.waitUntil(
    Promise.all([
      caches.open(SHELL_CACHE).then((cache) => cache.addAll(SHELL_URLS)),
      caches.open(LOCALE_CACHE).then((cache) => cache.add(REQUIRED_LOCALE_URL)),
    ])
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => (
        (key.startsWith('astral-shell-') && key !== SHELL_CACHE)
        || (key.startsWith(LOCALE_CACHE_PREFIX) && key !== LOCALE_CACHE)
      )).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/catalog/nasa-exoplanets/')) return;

  if (url.pathname.startsWith('/locales/') && url.pathname.endsWith('.json')) {
    event.respondWith(
      caches.open(LOCALE_CACHE).then(async (cache) => {
        try {
          const response = await fetch(request);
          if (response.ok) await cache.put(request, response.clone());
          return response;
        } catch {
          return (await cache.match(request)) ?? Response.error();
        }
      }),
    );
    return;
  }

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .catch(() => caches.match('/index.html').then((response) => response ?? Response.error())),
    );
    return;
  }

  if (SHELL_PATHS.has(url.pathname)) {
    event.respondWith(
      caches.open(SHELL_CACHE)
        .then((cache) => cache.match(url.pathname))
        .then((cached) => cached ?? fetch(request)),
    );
  }
});
`

await writeFile(resolve(DIST_ROOT, 'sw.js'), source, 'utf8')
process.stdout.write(`Generated offline shell ${revision} with ${urls.length} assets.\n`)
